// 主页冒烟：打开 → 主页两张卡 → 进 A → 结算点「换玩法」→ 进 B → 换回 A。
const { chromium } = require('/Users/chuyuannc/Downloads/Cursor/Kira/06_游戏设计/node_modules/playwright');
const path = require('path');
const fs = require('fs');
(async () => {
  const shots = path.join(__dirname, 'shots');
  fs.mkdirSync(shots, { recursive: true });
  const browser = await chromium.launch();
  const page = await browser.newPage({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2 });
  const errors = [];
  page.on('pageerror', (e) => errors.push(e.message));
  page.on('console', (m) => { if (m.type() === 'error') errors.push(m.text()); });
  const url = 'file://' + path.join(__dirname, '..', 'preview.html');
  await page.goto(url);
  await page.evaluate(() => localStorage.clear());
  await page.goto(url);
  await page.waitForTimeout(800);
  const check = (c, m) => { if (!c) throw new Error('没通过：' + m); console.log('  ✓ ' + m); };
  const g = (fn, a) => page.evaluate(fn, a);
  const M = await g(() => ({ scale: __menu.scale, ox: __menu.ox, oy: __menu.oy, cards: __menu.CARDS }));
  const tap = async (fx, fy, s) => { const sc = s || M; await page.mouse.click(sc.ox + fx * sc.scale, sc.oy + fy * sc.scale); };
  await page.screenshot({ path: path.join(shots, 'm1_主页.png') });
  check(typeof window === 'undefined' || (await g(() => typeof __ram === 'undefined' && typeof __moshou === 'undefined')), '主页先出来，两个玩法都还没加载');
  await tap(180, M.cards[0].y + 70);
  await page.waitForTimeout(600);
  check(await g(() => typeof __ram !== 'undefined' && __ram.G.mode === 'play'), '点 A 卡进机关龙');
  await g(() => { __ram.G.st.len = 1; });
  await page.waitForFunction(() => __ram.G.mode === 'result', null, { timeout: 30000 });
  await page.waitForTimeout(400);
  await page.screenshot({ path: path.join(shots, 'm2_A结算.png') });
  const A = await g(() => ({ scale: __ram.scale, ox: __ram.ox, oy: __ram.oy, b: __ram.G.buttons.find((x) => x.id === 'menu') }));
  await tap(A.b.x + A.b.w / 2, A.b.y + A.b.h / 2, A);
  await page.waitForTimeout(300);
  await tap(180, M.cards[1].y + 70);
  await page.waitForTimeout(900);
  check(await g(() => typeof __moshou !== 'undefined' && __moshou.G.mode === 'play'), '回主页点 B 卡进守城打龙');
  await page.screenshot({ path: path.join(shots, 'm3_B开局.png') });
  await g(() => { __moshou.G.st.hp = 0; __moshou.G.st.breach = 999; });
  check(errors.length === 0, '没有报错' + (errors.length ? '：' + errors.join(' | ') : ''));
  await browser.close();
  console.log('全部通过');
})().catch((e) => { console.error(e.message); process.exit(1); });
