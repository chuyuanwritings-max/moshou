// 《墨守》0.6 一攻一守：浏览器里走一遍 —— 主页 → 地图 → 简报 → 守城打一波 → 波间合机关、摆城墙、买东西 → 打完 → 结算 → 工坊 → 进攻关。
const { chromium } = require('/Users/chuyuannc/Downloads/Cursor/Kira/06_游戏设计/node_modules/playwright');
const path = require('path');
const fs = require('fs');
(async () => {
  const shots = path.join(__dirname, 'shots');
  fs.mkdirSync(shots, { recursive: true });
  const browser = await chromium.launch();
  const page = await browser.newPage({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2 });
  const errors = [];
  page.on('pageerror', (e) => errors.push(e.message));
  page.on('console', (m) => { if (m.type() === 'error') errors.push(m.text()); });
  const url = 'file://' + path.join(__dirname, '..', 'preview.html');
  await page.goto(url);
  await page.evaluate(() => localStorage.clear());
  await page.goto(url);
  await page.waitForTimeout(600);
  const check = (c, m) => { if (!c) throw new Error('没通过：' + m); console.log('  ✓ ' + m); };
  const g = (fn, a) => page.evaluate(fn, a);
  const snap = (n) => page.screenshot({ path: path.join(shots, n + '.png') });
  await page.screenshot({ path: path.join(shots, 'mo00_主页.png') });
  const MM = await g(() => ({ scale: __menu.scale, ox: __menu.ox, oy: __menu.oy, c: __menu.CARDS[0] }));
  await page.mouse.click(MM.ox + 180 * MM.scale, MM.oy + (MM.c.y + 60) * MM.scale);
  await page.waitForTimeout(500);
  check(await g(() => typeof __mo !== 'undefined' && __mo.G.scr === 'map'), '主页点「一攻一守」进边城地图');
  await snap('mo01_地图');
  const M = await g(() => ({ scale: __mo.scale, ox: __mo.ox, oy: __mo.oy }));
  const tapBtn = async (id) => {
    const b = await g((i) => __mo.G.btns.find((x) => x.id === i), id);
    if (!b) throw new Error('找不到按钮 ' + id);
    await page.mouse.click(M.ox + (b.x + b.w / 2) * M.scale, M.oy + (b.y + b.h / 2) * M.scale);
    await page.waitForTimeout(120);
  };
  await tapBtn('node0');
  check(await g(() => __mo.G.scr === 'brief'), '点第 1 关出简报（情节 + 选机关师）');
  check((await g(() => __mo.G.btns.filter((b) => b.id.startsWith('bld_')).length)) === 24, '简报里列出全部 24 个机关师');
  await tapBtn('bld_mogong');
  check(await g(() => __mo.G.bldView === 'mogong' && __mo.meta.builder === 'azhu'), '点没解锁的「墨工」：能看本事和解锁条件，但选不上');
  await snap('mo02_简报');
  await tapBtn('bld_azhu');
  await tapBtn('go');
  check(await g(() => __mo.G.scr === 'play' && __mo.G.r.lv.mode === 'defend'), '出发：守城');
  await page.waitForTimeout(1800);
  // 手指拖阿铸
  const x0 = await g(() => __mo.G.st.px);
  const sx = M.ox + 180 * M.scale, sy = M.oy + 650 * M.scale;
  await page.mouse.move(sx, sy); await page.mouse.down();
  for (let i = 1; i <= 8; i++) { await page.mouse.move(sx - i * 10, sy); await page.waitForTimeout(16); }
  await page.waitForTimeout(150);
  const xd = await g(() => __mo.G.st.px);
  await page.mouse.up();
  check(xd < x0 - 30, '想手动也行：按住拖，阿铸跟着走');
  await page.waitForFunction(() => __mo.G.st.dragons.length && __mo.G.st.dragons[0].segs.some((s) => s.s > 100), null, { timeout: 15000 });
  await page.waitForTimeout(800);
  const auto = await g(() => Math.abs(__mo.G.st.px - __mo.F.botX(__mo.G.st)) < 40);
  check(auto, '松手不管：阿铸自己瞄着最前面那一节射');
  await g(() => { __mo.G.bot = true; });
  await page.waitForFunction(() => __mo.G.st.dragons.length && __mo.G.st.dragons[0].segs.some((s) => s.s > 300), null, { timeout: 15000 });
  await snap('mo03_守城');
  check(true, '龙顺着弯路爬下来');
  await g(() => { __mo.G.bot = null; __mo.G.speed = 6; });
  await page.waitForFunction(() => __mo.G.scr === 'shop', null, { timeout: 30000 });
  await g(() => { __mo.G.speed = 1; });
  check(true, '倒计时到 0：龙当场全碎，进波间');
  await page.waitForTimeout(300);
  await snap('mo04_波间');
  // 属性卡
  while (await g(() => !!__mo.G.r.cards)) await tapBtn('card0');
  // 给点材料，合一件连弩、摆上城墙
  await g(() => { __mo.G.r.mats.jin += 4; __mo.G.r.coins += 100; });
  await tapBtn('mat_jin'); await tapBtn('mat_jin');
  await page.waitForTimeout(100);
  await snap('mo05_机关台');
  await tapBtn('combine');
  check((await g(() => __mo.G.r.log.made)) >= 1, '机关台：金 + 金 合出连弩');
  await tapBtn('slot0');
  check((await g(() => __mo.G.r.slots.some((x) => x && x.id === 'nu'))), '合好的连弩自动摆上城墙');
  await tapBtn('mat_jin'); await tapBtn('mat_jin'); await tapBtn('combine');
  await tapBtn('slot0');
  check((await g(() => __mo.G.r.slots.some((x) => x && x.id === 'nu' && x.tier === 2))), '再合一件连弩：自动叠上去升 2 阶');
  await tapBtn('buy0');
  check((await g(() => __mo.G.r.log.bought)) >= 1, '小店买东西');
  await snap('mo06_摆好');
  await tapBtn('nextWave');
  check(await g(() => __mo.G.scr === 'play' && __mo.G.r.wave === 1), '点「下一波」接着打');
  await page.waitForTimeout(2500);
  await snap('mo07_第二波');
  await g(() => { __mo.G.bot = true; __mo.G.speed = 8; __mo.G.r.hp = 999; __mo.G.r.hpMax = 999; });
  await page.waitForFunction(() => __mo.G.scr === 'result', null, { timeout: 60000 });
  await g(() => { __mo.G.speed = 1; __mo.G.bot = null; });
  await page.waitForTimeout(300);
  await snap('mo08_结算');
  check(await g(() => __mo.G.result.win && __mo.meta.cleared['1-1']), '守满 3 波过关，拿墨晶、残页、字块');
  await tapBtn('meta');
  await g(() => { __mo.meta.mojing += 500; __mo.meta.pages += 3; });
  await page.waitForTimeout(100);
  const s0 = await g(() => __mo.metaNow().slots);
  await tapBtn('up_slots');
  check((await g(() => __mo.metaNow().slots)) === s0 + 1, '工坊：花墨晶多开一个城墙点位');
  await tapBtn('rec_huixuan');
  check(await g(() => __mo.meta.recipes.indexOf('huixuan') >= 0), '工坊：花 3 张残页解锁配方「回旋刃」');
  await snap('mo09_工坊');
  // 进攻关
  await g(() => { __mo.meta.cleared['1-2'] = true; __mo.startLevel(2); });
  await page.waitForTimeout(1500);
  check(await g(() => __mo.G.r.lv.mode === 'attack' && __mo.G.r.slots[0] && __mo.G.r.slots[0].id === 'nu'), '1-3 进攻：开小工程车，车头自带连弩');
  await g(() => { __mo.G.bot = true; });
  await page.waitForTimeout(2500);
  await snap('mo10_进攻');
  await g(() => { __mo.G.speed = 6; });
  await page.waitForFunction(() => __mo.G.scr === 'shop' || __mo.G.scr === 'result', null, { timeout: 30000 });
  check(true, '冲到驿站，进波间机关台');
  await g(() => { __mo.G.speed = 1; });
  await page.waitForTimeout(200);
  await snap('mo11_驿站');
  await g(() => { __mo.meta.cleared['1-7'] = true; __mo.G.bot = true; __mo.startLevel(7); });
  await page.waitForTimeout(2000);
  await snap('mo12_机关龙');
  check(await g(() => __mo.G.st.car === 'dragon'), '1-8 开机关龙：一节一格');
  const fps = await g(() => new Promise((res) => { let n = 0; const t0 = performance.now(); const f = () => { n++; if (performance.now() - t0 < 2000) requestAnimationFrame(f); else res(n / 2); }; requestAnimationFrame(f); }));
  check(fps > 45, '帧率 ' + Math.round(fps));
  check(errors.length === 0, '没有报错' + (errors.length ? '：' + errors.slice(0, 3).join(' | ') : ''));
  await browser.close();
  console.log('全部通过');
})().catch((e) => { console.error(e.message); process.exit(1); });
